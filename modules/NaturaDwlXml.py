    """
    Fonction d'exécution pour BiblizouMain.
    
    Args:
        natura_layer (QgsVectorLayer): Couche Natura 2000 de référence
        folder_path (str): Chemin du dossier de téléchargement
    Returns:
        bool: True si le téléchargement a réussi, False sinon
    """
    module = NaturaDwlXml()
